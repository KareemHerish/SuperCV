export function getRotatedCandidateProjects(
  role: string,
  trackTitle: string,
  skills: string[],
  seed = 0
): AIProject[] {
  const roleLower = (role || '').toLowerCase();
  const trackLower = (trackTitle || '').toLowerCase();
  const skillsLower = (skills || []).map((s) => s.toLowerCase());

  const isAI =
    roleLower.includes('ai') ||
    roleLower.includes('data') ||
    roleLower.includes('machine') ||
    trackLower.includes('ai') ||
    trackLower.includes('data') ||
    skillsLower.some((s) => s.includes('python') || s.includes('pytorch') || s.includes('fastapi') || s.includes('tensorflow'));
  const isMobile =
    roleLower.includes('mobile') ||
    roleLower.includes('flutter') ||
    roleLower.includes('react native') ||
    roleLower.includes('android') ||
    roleLower.includes('ios') ||
    trackLower.includes('mobile');
  const isFrontend =
    roleLower.includes('front') ||
    roleLower.includes('react') ||
    roleLower.includes('next') ||
    roleLower.includes('vue') ||
    trackLower.includes('front');

  let pool: AIProject[];
  if (isAI) {
    pool = AI_DATA_PROJECTS;
  } else if (isMobile) {
    pool = MOBILE_PROJECTS;
  } else if (isFrontend) {
    pool = FRONTEND_PROJECTS;
  } else {
    pool = GENERAL_BACKEND_PROJECTS;
  }

  const selected: AIProject[] = [];
  const poolLen = pool.length;
  // Deterministic rotation: shift offset by (seed * 3)
  const offset = (Math.abs(seed) * 3) % poolLen;

  for (let i = 0; i < 5; i++) {
    const item = pool[(offset + i) % poolLen];
    selected.push({
      ...item,
      id: `${item.id}-s${seed}`,
    });
  }

  return selected;
}
